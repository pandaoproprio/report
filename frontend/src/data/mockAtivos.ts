// Helper functions
export const getCategoriaById = (categoriaId: string): CategoriaAtivo | undefined => {
  return mockCategorias.find(c => c.id === categoriaId);
};

export const getAtivoById = (ativoId: string): Ativo | undefined => {
  return mockAtivos.find(a => a.id === ativoId);
};

export const getEmprestimosByAtivoId = (ativoId: string): Emprestimo[] => {
  return mockEmprestimos.filter(e => e.ativo_id === ativoId);
};

export const getEmprestimosByUsuarioId = (usuarioId: string): Emprestimo[] => {
  return mockEmprestimos.filter(e => e.usuario_id === usuarioId);
};

export const getHistoricoByAtivoId = (ativoId: string): HistoricoAtivo[] => {
  return mockHistoricoAtivos.filter(h => h.ativo_id === ativoId).sort((a, b) =>
    new Date(b.data).getTime() - new Date(a.data).getTime()
  );
};

export const getAtivosDisponiveis = (): Ativo[] => {
  return mockAtivos.filter(a => a.status === 'disponivel');
};

export const getAtivosEmprestados = (): Ativo[] => {
  return mockAtivos.filter(a => a.status === 'emprestado');
};

export const getAtivosEmManutencao = (): Ativo[] => {
  return mockAtivos.filter(a => a.status === 'manutencao');
};

export const getEmprestimosAtivos = (): Emprestimo[] => {
  return mockEmprestimos.filter(e => e.status === 'ativo' || e.status === 'atrasado');
};

export const getEmprestimosAtrasados = (): Emprestimo[] => {
  return mockEmprestimos.filter(e => e.status === 'atrasado');
};
